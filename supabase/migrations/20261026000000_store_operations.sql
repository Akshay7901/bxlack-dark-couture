-- Store operations: readable order numbers, fulfilment + discount fields on
-- orders, admin-only order notes, discount codes, and automatic stock
-- deduction/restock. Run AFTER 20261024000000_return_requests.sql.

-- ---------------------------------------------------------------------------
-- 1. Orders: order number, fulfilment, pricing breakdown, stock flag
-- ---------------------------------------------------------------------------

-- Shopify-style #1001, #1002… Existing orders are numbered automatically.
alter table public.orders
  add column if not exists order_number bigint generated by default as identity (start with 1001);
create unique index if not exists orders_order_number_key on public.orders (order_number);

alter table public.orders
  add column if not exists courier text,
  add column if not exists tracking_number text,
  add column if not exists shipped_at timestamptz,
  add column if not exists subtotal numeric(10, 2),
  add column if not exists discount_code text,
  add column if not exists discount_amount numeric(10, 2) not null default 0,
  add column if not exists payment_method text not null default 'cod',
  -- true while this order's units are held out of inventory; flipped back to
  -- false when a cancellation returns them, so stock is never restored twice.
  add column if not exists stock_deducted boolean not null default false;

-- ---------------------------------------------------------------------------
-- 2. Stock: deduct/restock atomically. Sizes with no inventory row are
--    untracked (unlimited), matching how the product page treats them.
-- ---------------------------------------------------------------------------
create or replace function public.adjust_stock(p_items jsonb, p_direction integer)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  it jsonb;
  qty integer;
  pid uuid;
  sz text;
begin
  for it in select * from jsonb_array_elements(p_items) loop
    pid := (it->>'product_id')::uuid;
    sz := it->>'size';
    qty := (it->>'quantity')::integer;
    continue when pid is null or sz is null or qty is null or qty <= 0;

    if p_direction < 0 then
      update product_inventory
        set quantity = quantity - qty
        where product_id = pid and size = sz and quantity >= qty;
      if not found and exists (
        select 1 from product_inventory where product_id = pid and size = sz
      ) then
        -- Raising aborts the whole call, so earlier lines are rolled back too.
        raise exception 'OUT_OF_STOCK:%', coalesce(it->>'name', 'item') || ' (' || sz || ')';
      end if;
    else
      update product_inventory
        set quantity = quantity + qty
        where product_id = pid and size = sz;
    end if;
  end loop;
end;
$$;

revoke all on function public.adjust_stock(jsonb, integer) from public, anon, authenticated;
grant execute on function public.adjust_stock(jsonb, integer) to service_role;

-- Status side effects, whoever changes the status (admin studio or the
-- customer cancelling): stamp shipped_at, and restock cancelled orders.
create or replace function public.orders_status_effects()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.status = 'shipped' and old.status is distinct from 'shipped' then
    new.shipped_at := coalesce(new.shipped_at, now());
  end if;

  if new.status = 'cancelled' and old.status is distinct from 'cancelled' and old.stock_deducted then
    perform public.adjust_stock(
      (select coalesce(jsonb_agg(jsonb_build_object(
          'product_id', product_id, 'size', size, 'quantity', quantity)), '[]'::jsonb)
       from order_items where order_id = new.id),
      1
    );
    new.stock_deducted := false;
  end if;

  return new;
end;
$$;

drop trigger if exists orders_status_effects on public.orders;
create trigger orders_status_effects
before update of status on public.orders
for each row execute function public.orders_status_effects();

-- ---------------------------------------------------------------------------
-- 3. Internal order notes — admins only, never readable by the customer
--    (customers can select their own orders rows, so this can't live there).
-- ---------------------------------------------------------------------------
create table if not exists public.order_notes (
  order_id uuid primary key references public.orders(id) on delete cascade,
  note text not null default '',
  updated_at timestamptz not null default now()
);
alter table public.order_notes enable row level security;
grant all on public.order_notes to service_role;

create trigger order_notes_set_updated_at before update on public.order_notes
for each row execute function public.set_updated_at();

-- ---------------------------------------------------------------------------
-- 4. Discount codes — managed and validated only through the server.
-- ---------------------------------------------------------------------------
create table if not exists public.discount_codes (
  id uuid primary key default gen_random_uuid(),
  code text not null unique check (code = upper(code) and length(code) between 2 and 40),
  type text not null check (type in ('percent', 'fixed')),
  value numeric(10, 2) not null check (value > 0),
  min_order numeric(10, 2) not null default 0,
  max_uses integer check (max_uses is null or max_uses > 0),
  used_count integer not null default 0,
  starts_at timestamptz,
  ends_at timestamptz,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (type <> 'percent' or value <= 100)
);
alter table public.discount_codes enable row level security;
grant all on public.discount_codes to service_role;

create trigger discount_codes_set_updated_at before update on public.discount_codes
for each row execute function public.set_updated_at();

-- Validates a code against a subtotal and returns the discount in rupees.
-- With p_redeem = true it also consumes one use, atomically, so a limited
-- code can't be over-redeemed by simultaneous checkouts.
create or replace function public.apply_discount_code(
  p_code text,
  p_subtotal numeric,
  p_redeem boolean default false
)
returns numeric
language plpgsql
security definer
set search_path = public
as $$
declare
  d discount_codes%rowtype;
  amount numeric;
begin
  select * into d from discount_codes where code = upper(trim(p_code))
    for update;
  if not found or not d.active then
    raise exception 'DISCOUNT:This code isn''t valid.';
  end if;
  if d.starts_at is not null and now() < d.starts_at then
    raise exception 'DISCOUNT:This code isn''t active yet.';
  end if;
  if d.ends_at is not null and now() > d.ends_at then
    raise exception 'DISCOUNT:This code has expired.';
  end if;
  if d.max_uses is not null and d.used_count >= d.max_uses then
    raise exception 'DISCOUNT:This code has reached its usage limit.';
  end if;
  if p_subtotal < d.min_order then
    raise exception 'DISCOUNT:Spend at least ₹% to use this code.', d.min_order;
  end if;

  if d.type = 'percent' then
    amount := round(p_subtotal * d.value / 100);
  else
    amount := d.value;
  end if;
  amount := least(amount, p_subtotal);

  if p_redeem then
    update discount_codes set used_count = used_count + 1 where id = d.id;
  end if;
  return amount;
end;
$$;

revoke all on function public.apply_discount_code(text, numeric, boolean) from public, anon, authenticated;
grant execute on function public.apply_discount_code(text, numeric, boolean) to service_role;

-- Gives a use back when an order fails after the code was redeemed.
create or replace function public.release_discount_code(p_code text)
returns void
language sql
security definer
set search_path = public
as $$
  update discount_codes set used_count = greatest(used_count - 1, 0)
  where code = upper(trim(p_code));
$$;

revoke all on function public.release_discount_code(text) from public, anon, authenticated;
grant execute on function public.release_discount_code(text) to service_role;
